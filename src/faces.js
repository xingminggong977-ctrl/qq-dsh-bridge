/**
 * 把一个表情段翻成她能读的标记。
 *
 * 顺序很重要：服务端给的文字（`summary` / `raw.faceText`，形如 `/偷笑`）最准，
 * 优先用；没有才查表；再没有就把 id 亮出来——**看得见缺口，好过假装看懂**。
 */
export function faceMarker(segment, { sticker = false } = {}) {
	const data = segment?.data ?? {};
	const given = String(data.summary ?? data.raw?.faceText ?? '').trim();
	if (given !== '') return normalizeGiven(given);
	const id = String(data.id ?? '').trim();
	const named = FACE_NAMES[id];
	if (named !== undefined) return `[${named}]`;
	if (id !== '') return sticker ? `[表情包#${id}]` : `[表情#${id}]`;
	return sticker ? '[表情包]' : '[表情]';
}

/** `/偷笑` 一律变成 `[偷笑]`；已经是 `[偷笑]` 的不重复套壳。 */
function normalizeGiven(text) {
	const bare = text.replace(/^\/+/, '').trim();
	if (bare === '') return '[表情]';
	return bare.startsWith('[') ? bare : `[${bare}]`;
}
